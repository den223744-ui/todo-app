"""Anonymous workspaces: every visitor gets their own task list without signing up."""

import uuid

from sqlalchemy.ext.asyncio import AsyncSession

from app.models import Workspace


def parse_workspace_id(raw: str | None) -> uuid.UUID | None:
    """Parse the id from the session cookie; anything malformed counts as absent."""
    if not raw:
        return None
    try:
        return uuid.UUID(raw)
    except ValueError:
        return None


async def get_or_create_workspace(session: AsyncSession, raw_id: str | None) -> Workspace:
    """Return the workspace from the cookie value, or create a fresh one.

    An unknown id is never adopted as the id of a new workspace: ids are always
    generated by the server, so a client cannot pick its own (session fixation).
    """
    workspace_id = parse_workspace_id(raw_id)
    if workspace_id is not None:
        workspace = await session.get(Workspace, workspace_id)
        if workspace is not None:
            return workspace

    workspace = Workspace()
    session.add(workspace)
    await session.commit()
    return workspace
